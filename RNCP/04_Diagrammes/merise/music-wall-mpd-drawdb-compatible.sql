    CONSTRAINT fkanjlpxh3woomkmjv56avw9qcf FOREIGN KEY (user_id) REFERENCES public.app_user(id),
    CONSTRAINT fktbu4udnko8pjm1fj05ys5nqec FOREIGN KEY (wall_id) REFERENCES public.music_wall(id)
