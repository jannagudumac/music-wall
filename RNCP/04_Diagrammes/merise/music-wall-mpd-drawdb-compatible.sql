CREATE TABLE public.music_section (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name varchar(80) NOT NULL,
    note_color varchar(20),
    wall_id bigint NOT NULL,
    CONSTRAINT music_section_pkey PRIMARY KEY (id),
    CONSTRAINT fkh0jyhi45mj23y0erkghc80u16 FOREIGN KEY (wall_id) REFERENCES public.music_wall(id)
