package com.musicwall.dto;

// DTO returns only the artist's id and name for searches and detail pages.
public class ArtistDTO {

    private Long id;
    private String name;

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

}
