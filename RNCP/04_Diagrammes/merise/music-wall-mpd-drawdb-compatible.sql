    wallpaper varchar(20),
    owner_id bigint NOT NULL,
    CONSTRAINT music_wall_pkey PRIMARY KEY (id),
    CONSTRAINT fk4v9ryrcu2jq33soqkon4ce8y5 FOREIGN KEY (owner_id) REFERENCES public.app_user(id)
);

CREATE TABLE public.wall_members (
    wall_id bigint NOT NULL,
